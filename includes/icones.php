/** Devolve o desenho pronto (<svg>) de um ícone. Se o nome não existir, usa a estrela. */
function icone(string $nome, string $classe = ''): string
{
    $desenho = ICONES_SVG[$nome] ?? ICONES_SVG['estrela'];
    $extra = $classe !== '' ? ' ' . h($classe) : '';
    return '<svg class="icone' . $extra . '" viewBox="0 0 24 24" aria-hidden="true" focusable="false">' . $desenho . '</svg>';
}
